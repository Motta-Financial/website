#!/usr/bin/env node
/**
 * Build a trimmed Font Awesome: only the icons this site actually uses.
 *
 *   node scripts/build-fa-subset.mjs        (needs: pip install fonttools brotli)
 *
 * Why: the full Font Awesome 5 set is ~170 KB of woff2 plus a 58 KB stylesheet
 * with ~1,500 icon rules, and every page downloaded all of it for a few dozen
 * icons. This reads fontawesome-all.min.css, finds every `fa-*` class mentioned
 * in the source (app/, components/, lib/, util/) or in the site stylesheets, plus
 * every `content: "\f…"` glyph the site CSS draws itself, and writes:
 *   public/assets/css/fontawesome-subset.css       (what app/layout.js imports)
 *   public/assets/fonts/fa-{solid-900,regular-400,brands-400}.subset.woff2
 * The original files stay untouched, so run this again after using a new icon.
 * Set PYFTSUBSET to the pyftsubset binary if it isn't on your PATH.
 */
import fs from 'node:fs';
import path from 'node:path';
import { execFileSync } from 'node:child_process';

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
const cssDir = path.join(root, 'public/assets/css');
const fontDir = path.join(root, 'public/assets/fonts');
const pyftsubset = process.env.PYFTSUBSET || 'pyftsubset';

function walk(dir, exts, out = []) {
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    if (e.name === 'node_modules' || e.name === '.next' || e.name.startsWith('.')) continue;
    const p = path.join(dir, e.name);
    if (e.isDirectory()) walk(p, exts, out);
    else if (exts.includes(path.extname(e.name))) out.push(p);
  }
  return out;
}

const faCss = fs.readFileSync(path.join(cssDir, 'fontawesome-all.min.css'), 'utf8');

// 1) which fa-* class names does the site mention?
const sources = ['app', 'components', 'lib', 'util'].flatMap((d) => walk(path.join(root, d), ['.js', '.json']));
const siteCss = ['main.css', 'motta.css', 'default.css', 'responsive.css'].map((f) => fs.readFileSync(path.join(cssDir, f), 'utf8'));
const usedClasses = new Set();
let dynamic = 0;
for (const text of [...sources.map((f) => fs.readFileSync(f, 'utf8')), ...siteCss]) {
  for (const m of text.matchAll(/\bfa-([a-z0-9-]+)/g)) usedClasses.add(m[1]);
  dynamic += (text.match(/fa-\$\{/g) || []).length;
}
if (dynamic) console.warn(`WARNING: ${dynamic} dynamic "fa-\${…}" class(es) found — those icons can't be detected.`);

// 2) glyphs the site stylesheets draw directly with content: "\f…"
const cssGlyphs = new Set();
for (const css of siteCss) for (const m of css.matchAll(/content:\s*["']\\(f[0-9a-f]{3})["']/gi)) cssGlyphs.add(m[1].toLowerCase());

// 3) split the minified Font Awesome stylesheet into top-level rules and keep what's needed
const rules = [];
for (let i = 0, depth = 0, start = 0; i < faCss.length; i++) {
  if (faCss[i] === '{') depth++;
  else if (faCss[i] === '}' && --depth === 0) { rules.push(faCss.slice(start, i + 1)); start = i + 1; }
}
const iconRule = /^((?:\.fa-[a-z0-9-]+:before,?)+)\{content:"\\([0-9a-f]+)"\}$/;
const keepCodes = new Set(cssGlyphs);
const kept = [];
let totalIcons = 0, keptIcons = 0;
for (const rule of rules) {
  if (rule.startsWith('@font-face')) continue; // replaced below
  const m = rule.match(iconRule);
  if (!m) { kept.push(rule); continue; }
  totalIcons++;
  const names = [...m[1].matchAll(/\.fa-([a-z0-9-]+):before/g)].map((x) => x[1]);
  if (names.some((n) => usedClasses.has(n))) { kept.push(rule); keptIcons++; keepCodes.add(m[2].toLowerCase()); }
}

// 4) subset the three woff2 fonts to those code points
const unicodes = [...keepCodes].map((c) => 'U+' + c).join(',');
const faces = [
  { family: 'Font Awesome 5 Brands', weight: 400, file: 'fa-brands-400' },
  { family: 'Font Awesome 5 Free', weight: 400, file: 'fa-regular-400' },
  { family: 'Font Awesome 5 Free', weight: 900, file: 'fa-solid-900' },
];
let fontBytes = 0;
const fontFaces = faces.map((f) => {
  const out = path.join(fontDir, `${f.file}.subset.woff2`);
  execFileSync(pyftsubset, [path.join(fontDir, `${f.file}.woff2`), `--unicodes=${unicodes}`, '--flavor=woff2', '--layout-features=*', `--output-file=${out}`]);
  fontBytes += fs.statSync(out).size;
  return `@font-face{font-family:"${f.family}";font-style:normal;font-weight:${f.weight};font-display:block;src:url(../fonts/${f.file}.subset.woff2) format("woff2")}`;
});

const header = `/* GENERATED by scripts/build-fa-subset.mjs — do not edit by hand. */\n`;
fs.writeFileSync(path.join(cssDir, 'fontawesome-subset.css'), header + fontFaces.join('\n') + '\n' + kept.join('\n') + '\n');
console.log(`icons kept: ${keptIcons} of ${totalIcons}; extra css glyphs: ${cssGlyphs.size}; subset fonts: ${(fontBytes / 1024).toFixed(1)} KB total`);
console.log(`css: ${(faCss.length / 1024).toFixed(1)} KB -> ${(fs.statSync(path.join(cssDir, 'fontawesome-subset.css')).size / 1024).toFixed(1)} KB`);
